# NOTEBOOK INITIALIZATION
# ============================================================
"""
    Create the first notebook cell.

    This cell loads the dataset and initializes the variables
    that the LLM-generated cells will use.
"""
def create_init_cell(input_path: str) -> str:
    return f"""
        import json
        import pandas as pd
        from pathlib import Path

        # Load the original dataset.
        input_path = Path({str(input_path)!r})
        df = pd.read_csv(input_path)

        # Normalize empty and whitespace-only cells.
        for col in df.columns:
            if pd.api.types.is_object_dtype(df[col]) or pd.api.types.is_string_dtype(df[col]):
                df[col] = df[col].replace(r"^\s*$", pd.NA, regex=True)

        # Store results from each planned operation.
        operation_results = {{}}

        # Record the original dataset dimensions.
        initial_rows = len(df)
        initial_columns = len(df.columns)

        print("Dataset loaded successfully.")
        print(f"Initial rows: {{initial_rows}}")
        print(f"Initial columns: {{initial_columns}}")

    """


# ============================================================
# NOTEBOOK FINALIZATION
# ============================================================
"""
    Create the last notebook cell.

    It saves the prepared dataset and the results collected
    by the generated operation cells.
"""
def create_finalization_cell(output_dir: Path) -> str:
    cleaned_path = output_dir / "cleaned.csv"
    results_path = output_dir / "operation_results.json"

    return f"""
        from pathlib import Path
        import json

        # Output paths are controlled by the notebook runner.
        prepared_path = Path({str(cleaned_path)!r})
        results_path = Path({str(results_path)!r})

        prepared_path.parent.mkdir(parents=True, exist_ok=True)

        # Save the prepared dataset.
        df.to_csv(prepared_path, index=False)

        # Collect results from the generated operation cells.
        with results_path.open("w", encoding="utf-8") as file:
            json.dump(
                operation_results,
                file,
                indent=2,
                default=lambda value: (
                    value.item()
                    if hasattr(value, "item")
                    else str(value)
                ),
            )

        print("Notebook execution completed.")
        print(f"Prepared dataset saved to: {{prepared_path}}")
        print(f"Operation results saved to: {{results_path}}")
        print(f"Final dataset shape: {{df.shape}}")
    """



# ============================================================
# NOTEBOOK CONSTRUCTION
# ============================================================
"""
    Build a notebook from the initialization cell,
    LLM-generated cells and finalization cell.
"""
def build_notebook(generated_code: GeneratedNotebookCode, input_path: Path, output_path: Path):
    notebook = new_notebook()
    notebook.metadata.kernelspec = {
        "display_name": "Python 3",
        "language": "python",
        "name": "python3",
    }
    notebook.metadata.language_info = {
        "name": "python"
    }

    cells = []

    # First cell: Load the dataset
    cells.append(new_code_cell(source=create_init_cell(input_path)))
    
    # Middle cells: code generated by LLM
    for generated_cell in generated_code.cells:
        cell_source = (
            f"# Step {generated_cell.step}: "
            f"{generated_cell.title}\n\n"
            f"{generated_cell.code}"
        )
        cells.append(new_code_cell(source=cell_source))

    # Last cell: Save the prepared dataset and operation results
    cells.append(new_code_cell(source=create_finalization_cell(output_path)))

    notebook.cells = cells
    return notebook


# ============================================================
# NOTEBOOK EXECUTION
# ============================================================
"""
    Build and execute the generated preparation notebook.

    Args:
        generated_code:
            GeneratedNotebookCode returned by code_generator.py.

        input_path:
            Path to the original CSV dataset.

        output_dir:
            Directory in which notebook outputs are stored.

        timeout:
            Maximum execution time per notebook cell, in seconds.

    Returns:
        prepared_df:
            The prepared dataset loaded from prepared.csv.

        report:
            A dictionary containing execution results and
            information about the generated artifacts.
"""
def run_notebook(generated_code, input_path: str | Path, output_dir: str | Path, timeout: int = 300) -> tuple[pd.DataFrame, dict[str, Any]]:
    input_path = Path(input_path).expanduser().resolve()
    output_dir = Path(output_dir).expanduser().resolve()

    if not input_path.is_file():
        raise FileNotFoundError(f"Input dataset does not exist: {input_path}")
    
    output_dir.mkdir(parents=True, exist_ok=True)

    notebook_path = output_dir / "preparation.ipynb"
    results_path = output_dir / "operation_results.json"
    cleaned_path = output_dir / "cleaned.csv"

    # 1. Build the notebook.
    notebook = build_notebook(generated_code=generated_code, input_path=input_path, output_path=output_dir)
    nbformat.write(notebook, notebook_path)

    # 2. Execute the notebook.
    client = NotebookClient(
        notebook,
        timeout = timeout,
        kernel_name = "python3",
        resources = {
            "metadata": {
                "path": str(output_dir),
            }
        },
        allow_errors = False,
    )

    try:
        client.execute()

    except Exception as exc:
        # Preserve the notebook, including outputs and the
        # error from the cell that failed.
        nbformat.write(notebook, notebook_path)
        failed_cell = None
        for index, cell in enumerate(notebook.cells):
            if cell.cell_type != "code":
                continue
            for output in cell.get("outputs", []):
                if output.get("output_type") == "error":
                    failed_cell = index
                    break

            if failed_cell is not None:
                break

        report = {
            "status": "failed",
            "error": str(exc),
            "failed_cell_index": failed_cell,
            "notebook_path": str(notebook_path),
        }

        # Save the failure report separately.
        failure_report_path = output_dir / "execution_error.json"
        failure_report_path.write_text(
            json.dumps(report, indent=2),
            encoding="utf-8",
        )

        raise RuntimeError(
            f"Notebook execution failed. "
            f"Inspect {notebook_path} for details. "
            f"Original error: {exc}"
        ) from exc
    
    finally:
        # Stop the separate Jupyter kernel.
        if client.km is not None:
            client.km.shutdown_kernel(now=True)

    # Save the successfully executed notebook, including outputs.
    nbformat.write(notebook, notebook_path)

    # 3. Check the expected artifacts.
    if not cleaned_path.is_file():
        raise RuntimeError("Notebook finished without producing prepared.csv.")
    
    if not results_path.is_file():
        raise RuntimeError("Notebook finished without producing operation_results.json.")
    
    # 4. Load the results collected by the notebook.
    with results_path.open("r", encoding="utf-8") as file:
        operation_results = json.load(file)

    cleaned_df = pd.read_csv(cleaned_path)     # Load the prepared dataset into the main CloudFlow process.

    # 5. Build the execution report.
    original_df = pd.read_csv(input_path)
    report = {
        "status": "completed",
        "rows_before": int(len(original_df)),
        "columns_before": int(len(original_df.columns)),
        "rows_after": int(len(cleaned_df)),
        "columns_after": int(len(cleaned_df.columns)),
        "rows_removed": int(
            len(original_df) - len(cleaned_df)
        ),
        "column_names": [
            str(column) for column in cleaned_df.columns
        ],
        "missing_values_after": {
            str(column): int(cleaned_df[column].isna().sum())
            for column in cleaned_df.columns
        },
        "data_types_after": {
            str(column): str(cleaned_df[column].dtype)
            for column in cleaned_df.columns
        },
        "operation_results": operation_results,
        "artifacts": {
            "notebook": str(notebook_path),
            "prepared_dataset": str(cleaned_path),
            "operation_results": str(results_path),
        },
    }

    # Save the report collected by the runner.
    report_path = output_dir / "preparation_report.json"

    with report_path.open("w", encoding="utf-8") as file:
        json.dump(report, file, indent=2, default=str)

    return cleaned_df, report